function [lhs, rhs] = static_resid(y, x, params)
T = NaN(0, 1);
lhs = NaN(7, 1);
rhs = NaN(7, 1);
lhs(1) = y(3);
rhs(1) = y(5)-y(1);
lhs(2) = params(1)*y(4);
rhs(2) = y(4)-y(1);
lhs(3) = y(1);
rhs(3) = y(1)+params(3)*params(4)*(y(6)+y(7)-y(4));
lhs(4) = y(2);
rhs(4) = 0;
lhs(5) = y(5);
rhs(5) = y(5)*params(5)+x(1);
lhs(6) = y(6);
rhs(6) = y(6)*params(7)+x(2);
lhs(7) = y(7);
rhs(7) = (-y(6));
end
